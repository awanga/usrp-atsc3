// pilot_additional_cp_gen.cc — additional continual-pilot table generator
// for hdl/rtl/ofdm/pilot_extractor.v
//
// Emits hdl/rtl/ofdm/pilot_additional_cp_lut.v: one case item per allowed
// {FFT size, scattered pilot pattern, carrier reduction} combination, from
// lib/ofdm/pilot_extractor.h's additional_continual_pilots() (A/322 Tables
// D.1.4 and D.1.5). The case selector `key` is {fft_sel[1:0] (0 = 8K, 1 =
// 16K, 2 = 32K), pattern[3:0], cred[2:0]}; an item sets `ok` and up to
// three relative carrier indices v0..v2 with their enables `en`. A key with
// no item is a combination the standard does not allow (ok = 0).
//
// Usage: pilot_additional_cp_gen > hdl/rtl/ofdm/pilot_additional_cp_lut.v

#include "ofdm/pilot_extractor.h"

#include <cstdio>
#include <vector>

int main() {
    using atsc3::ofdm::PilotPattern;

    std::printf(
        "// SPDX-License-Identifier: CERN-OHL-W-2.0\n"
        "// SPDX-FileCopyrightText: 2026 Alfred Wanga\n"
        "//\n"
        "// pilot_additional_cp_lut.v -- GENERATED by hdl/sim/golden/pilot_additional_cp_gen; do not\n"
        "// edit. Additional scattered-pilot-bearing continual pilots (A/322 Tables D.1.4, D.1.5)\n"
        "// per key = {fft_sel, pattern, cred} = {2, 4, 3} bits; absent keys are not allowed.\n"
        "\n"
        "module pilot_additional_cp_lut (\n"
        "    input  wire [8:0]  key,\n"
        "    output reg         ok,\n"
        "    output reg  [2:0]  en,\n"
        "    output reg  [13:0] v0,\n"
        "    output reg  [13:0] v1,\n"
        "    output reg  [13:0] v2\n"
        ");\n"
        "\n"
        "    always @(*) begin\n"
        "        ok = 1'b0;\n"
        "        en = 3'b000;\n"
        "        v0 = 14'd0;\n"
        "        v1 = 14'd0;\n"
        "        v2 = 14'd0;\n"
        "        case (key)\n");
    for (size_t fft_sel = 0; fft_sel < 3; ++fft_sel) {
        const size_t fft_size = 8192u << fft_sel;
        for (size_t code = 0; code < 16; ++code) {
            const auto pattern = static_cast<PilotPattern>(code);
            if (!atsc3::ofdm::pilot_pattern_allowed(fft_size, pattern)) {
                continue;
            }
            for (size_t cred = 0; cred <= 4; ++cred) {
                const std::vector<size_t> cps =
                    atsc3::ofdm::additional_continual_pilots(fft_size, pattern, cred);
                if (cps.size() > 3) {
                    std::fprintf(stderr, "pilot_additional_cp_gen: more than 3 additional CPs\n");
                    return 1;
                }
                unsigned enables = 0;
                size_t value[3] = {0, 0, 0};
                for (size_t i = 0; i < cps.size(); ++i) {
                    enables |= 1u << i;
                    value[i] = cps[i];
                }
                std::printf(
                    "            9'd%zu: begin ok = 1'b1; en = 3'b%u%u%u; v0 = 14'd%zu; v1 = 14'd%zu; "
                    "v2 = 14'd%zu; end\n",
                    (fft_sel << 7) | (code << 3) | cred, (enables >> 2) & 1u, (enables >> 1) & 1u,
                    enables & 1u, value[0], value[1], value[2]);
            }
        }
    }
    std::printf(
        "            default: ;\n"
        "        endcase\n"
        "    end\n"
        "\n"
        "endmodule\n");
    return 0;
}
