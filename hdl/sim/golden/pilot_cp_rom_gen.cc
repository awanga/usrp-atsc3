// pilot_cp_rom_gen.cc — common continual-pilot ROM generator for
// hdl/rtl/ofdm/pilot_extractor.v
//
// Dumps the common continual pilot set CP32 (A/322 Table D.1.1) as the
// model holds it: ascending absolute carrier indices for the 32K FFT,
// from lib/ofdm/pilot_extractor.h's common_continual_pilots(). The RTL
// derives the 16K and 8K sets from it the way Section 8.1.4.1 does (every
// 2nd / 4th entry, halved / quartered, rounded up).
//
// Output (stdout): a $readmemh file for pilot_extractor.v's cp_rom, 256
// 16-bit words: the 192 entries from address 0, then FFFF end markers (no
// carrier index has bit 15 set).
//
// Usage: pilot_cp_rom_gen > hdl/rtl/ofdm/pilot_cp_positions.hex

#include "ofdm/pilot_extractor.h"

#include <cstdint>
#include <cstdio>
#include <vector>

int main() {
    constexpr size_t kRomDepth = 256;
    constexpr uint16_t kEnd = 0xFFFF;

    const std::vector<size_t> cp32 = atsc3::ofdm::common_continual_pilots(32768);
    if (cp32.size() != 192) {
        std::fprintf(stderr, "pilot_cp_rom_gen: expected 192 CP32 entries, got %zu\n", cp32.size());
        return 1;
    }

    std::vector<uint16_t> rom(kRomDepth, kEnd);
    for (size_t i = 0; i < cp32.size(); ++i) {
        rom[i] = static_cast<uint16_t>(cp32[i]);
    }

    std::printf(
        "// pilot_cp_positions.hex -- GENERATED by hdl/sim/golden/pilot_cp_rom_gen; do not edit.\n"
        "// Common continual pilot set CP32 (absolute carrier indices), ended by ffff.\n");
    for (uint16_t word : rom) {
        std::printf("%04x\n", word);
    }
    return 0;
}
