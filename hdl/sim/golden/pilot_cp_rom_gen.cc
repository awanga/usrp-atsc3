// pilot_cp_rom_gen.cc — continual-pilot ROM generator for
// hdl/rtl/ofdm/pilot_extractor.v
//
// Dumps the continual-pilot positions of the real PilotExtractor
// (lib/ofdm/pilot_extractor.cc) for each FFT size, relative to the first
// active carrier. Each extractor is built with every carrier active
// (first active carrier 0), so the list holds every candidate position;
// a smaller active window only truncates it, which the RTL does by
// comparing against the carrier's relative index.
//
// Output (stdout): a $readmemh file for pilot_extractor.v's cp_rom, 1024
// 16-bit words: 8K positions from address 0, 16K from 256, 32K from 512,
// each ascending and terminated by FFFF (no relative index has bit 15 set).
//
// Usage: pilot_cp_rom_gen > hdl/rtl/ofdm/pilot_cp_positions.hex

#include "ofdm/pilot_extractor.h"

#include <cstdint>
#include <cstdio>
#include <vector>

int main() {
    using atsc3::sample_t;
    using atsc3::ofdm::PilotExtractor;
    using atsc3::ofdm::PilotExtractorConfig;

    constexpr size_t kRomDepth = 1024;
    constexpr uint16_t kEnd = 0xFFFF;
    const size_t fft_sizes[] = {8192, 16384, 32768};
    const size_t bases[] = {0, 256, 512, kRomDepth};

    std::vector<uint16_t> rom(kRomDepth, kEnd);
    for (size_t i = 0; i < 3; ++i) {
        PilotExtractorConfig config;
        config.fft_size = fft_sizes[i];
        config.num_active_carriers = fft_sizes[i];
        PilotExtractor extractor(config);
        if (extractor.get_pattern_params().first_active != 0) {
            std::fprintf(stderr, "pilot_cp_rom_gen: first active carrier not 0\n");
            return 1;
        }

        std::vector<sample_t> zeros(fft_sizes[i], sample_t(0, 0));
        auto pilots = extractor.extract_continual(zeros.data());
        if (pilots.size() >= bases[i + 1] - bases[i]) {
            std::fprintf(stderr, "pilot_cp_rom_gen: %zu positions overflow the %zu-entry region\n",
                         pilots.size(), bases[i + 1] - bases[i]);
            return 1;
        }
        for (size_t j = 0; j < pilots.size(); ++j) {
            rom[bases[i] + j] = static_cast<uint16_t>(pilots[j].subcarrier_index);
        }
    }

    std::printf(
        "// pilot_cp_positions.hex -- GENERATED by hdl/sim/golden/pilot_cp_rom_gen; do not edit.\n"
        "// Continual-pilot carrier offsets from the first active carrier: 8K at 0, 16K at\n"
        "// 256, 32K at 512, each ascending and ended by ffff.\n");
    for (uint16_t word : rom) {
        std::printf("%04x\n", word);
    }
    return 0;
}
