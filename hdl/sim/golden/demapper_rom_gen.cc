// demapper_rom_gen.cc — non-uniform constellation ROM generator for
// hdl/rtl/ofdm/constellation_demapper.v
//
// Reads the Q1.15 constellation points the model actually builds
// (ConstellationDemapper::constellation_points(), headroom scaling and
// float_to_q15 truncation included), so the ROMs hold what the golden model
// compares against, not a re-derivation of the float tables.
//
//   2d: first-quadrant points {re[15:0], im[15:0]} of the 2D-NUC modes,
//       NUC_16 (4 per code rate, ROM addresses 0..47), NUC_64 (16 per rate,
//       48..239), NUC_256 (64 per rate, 240..1007). The model's full
//       constellation is the quadrant expansion of Tables C.1.2-C.1.7
//       (points[q*N + i]: q0 (+,+), q1 (-,+), q2 (+,-), q3 (-,-)); this
//       generator checks that against the model for every point.
//   1d: per-axis level magnitudes of the 1D-NUC modes, NUC_1024 (32 per rate,
//       addresses 0..383), NUC_4096 (64 per rate, 384..1151), 16 bits each,
//       indexed by the full per-axis index (sign = its MSB), checked against
//       the model's points for every index on both axes.
//
// Usage: demapper_rom_gen 2d > hdl/rtl/ofdm/nuc2d.hex
//        demapper_rom_gen 1d > hdl/rtl/ofdm/nuc1d.hex

#include "ofdm/constellation_demapper.h"

#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <vector>

using atsc3::config::CodeRate;
using atsc3::config::Modulation;
using atsc3::ofdm::ConstellationDemapper;
using atsc3::ofdm::DemapperConfig;

namespace {

std::vector<atsc3::sample_t> points_for(Modulation mod, int rate) {
    DemapperConfig cfg;
    cfg.modulation = mod;
    cfg.code_rate = static_cast<CodeRate>(rate);
    return ConstellationDemapper(cfg).constellation_points();
}

[[noreturn]] void fail(const char* msg) {
    std::fprintf(stderr, "demapper_rom_gen: %s\n", msg);
    std::exit(1);
}

void emit_2d() {
    std::printf(
        "// nuc2d.hex -- GENERATED by hdl/sim/golden/demapper_rom_gen 2d; do not edit.\n"
        "// First-quadrant Q1.15 points {re, im}: NUC_16 (4 per code rate) at 0, NUC_64 (16)\n"
        "// at 48, NUC_256 (64) at 240.\n");
    const struct {
        Modulation mod;
        size_t n;
    } kModes[] = {{Modulation::NUC_16, 4}, {Modulation::NUC_64, 16}, {Modulation::NUC_256, 64}};
    for (const auto& m : kModes) {
        for (int rate = 0; rate < 12; ++rate) {
            const auto pts = points_for(m.mod, rate);
            if (pts.size() != 4 * m.n) {
                fail("unexpected 2D-NUC constellation size");
            }
            for (size_t i = 0; i < m.n; ++i) {
                const int16_t re = pts[i].real();
                const int16_t im = pts[i].imag();
                if (pts[m.n + i] != atsc3::sample_t(-re, im) ||
                    pts[2 * m.n + i] != atsc3::sample_t(re, -im) ||
                    pts[3 * m.n + i] != atsc3::sample_t(-re, -im)) {
                    fail("2D-NUC quadrant expansion does not match the model");
                }
                std::printf("%04x%04x\n", static_cast<uint16_t>(re), static_cast<uint16_t>(im));
            }
        }
    }
}

void emit_1d() {
    std::printf(
        "// nuc1d.hex -- GENERATED by hdl/sim/golden/demapper_rom_gen 1d; do not edit.\n"
        "// Per-axis level magnitudes (Q1.15): NUC_1024 (32 per code rate) at 0, NUC_4096\n"
        "// (64) at 384; index = full per-axis index, sign = its MSB.\n");
    const struct {
        Modulation mod;
        int bits;  // bits per axis
    } kModes[] = {{Modulation::NUC_1024, 5}, {Modulation::NUC_4096, 6}};
    for (const auto& m : kModes) {
        const size_t side = size_t(1) << m.bits;
        for (int rate = 0; rate < 12; ++rate) {
            const auto pts = points_for(m.mod, rate);
            if (pts.size() != side * side) {
                fail("unexpected 1D-NUC constellation size");
            }
            std::vector<int16_t> mag(side);
            for (size_t a = 0; a < side; ++a) {
                // Point index with per-axis index a on I (bit 2n of the
                // symbol index is bit n of the I index) and 0 on Q, and the
                // mirror for Q.
                size_t i_pt = 0;
                size_t q_pt = 0;
                for (int n = 0; n < m.bits; ++n) {
                    i_pt |= ((a >> n) & 1u) << (2 * n);
                    q_pt |= ((a >> n) & 1u) << (2 * n + 1);
                }
                const int16_t level_i = pts[i_pt].real();
                const int16_t level_q = pts[q_pt].imag();
                const bool neg = (a >> (m.bits - 1)) & 1u;
                const int16_t magnitude = neg ? -level_i : level_i;
                if (magnitude < 0 || (neg ? -level_q : level_q) != magnitude) {
                    fail("1D-NUC levels do not match the model's sign convention");
                }
                mag[a] = magnitude;
            }
            // Cartesian-product check: every point is (level_I, level_Q)
            for (size_t i = 0; i < pts.size(); ++i) {
                size_t ai = 0;
                size_t aq = 0;
                for (int n = 0; n < m.bits; ++n) {
                    ai |= ((i >> (2 * n)) & 1u) << n;
                    aq |= ((i >> (2 * n + 1)) & 1u) << n;
                }
                const int16_t li = ((ai >> (m.bits - 1)) & 1u) ? -mag[ai] : mag[ai];
                const int16_t lq = ((aq >> (m.bits - 1)) & 1u) ? -mag[aq] : mag[aq];
                if (pts[i] != atsc3::sample_t(li, lq)) {
                    fail("1D-NUC constellation is not the product of its axis levels");
                }
            }
            for (size_t a = 0; a < side; ++a) {
                std::printf("%04x\n", static_cast<uint16_t>(mag[a]));
            }
        }
    }
}

}  // namespace

int main(int argc, char** argv) {
    if (argc == 2 && std::strcmp(argv[1], "2d") == 0) {
        emit_2d();
    } else if (argc == 2 && std::strcmp(argv[1], "1d") == 0) {
        emit_1d();
    } else {
        std::fprintf(stderr, "usage: demapper_rom_gen 2d|1d\n");
        return 1;
    }
    return 0;
}
