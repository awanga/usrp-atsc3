"""Generate lib/fec/bit_interleaver_tables.h from the ATSC A/322 PDF (Annex B).

Annex B lists the group-wise interleaving order pi(j) of A/322 Section
6.2.2 for every modulation and code rate: Tables B.1.1-B.1.6 for
Ninner = 64800 (180 bit groups; QPSK to 4096QAM) and B.2.1-B.2.4 for
Ninner = 16200 (45 bit groups; QPSK to 256QAM).

Usage:
  scripts/gen_bit_interleaver_tables.py A322-2026-06.pdf > lib/fec/bit_interleaver_tables.h

The PDF is published by ATSC (https://www.atsc.org/atsc-documents/) and is
not redistributed here. Requires pypdf (BSD-3-Clause; 6.13.0 used).

Each table is printed as a header row j = 0..Ngroup-1 followed by one block
per code rate ("2/15" then Ngroup values). Every block is checked to be a
permutation of 0..Ngroup-1 and all 120 must be present; any failure exits
nonzero rather than emitting a partial header.
"""

import re
import sys

import pypdf

MODS = ["QPSK", "16QAM", "64QAM", "256QAM", "1024QAM", "4096QAM"]
CAPTION_RE = re.compile(
    r"^Table B\.([12])\.(\d) (QPSK|16QAM|64QAM|256QAM|1024QAM|4096QAM) "
    r"\((?:Ninner|Code length) = (64800|16200)(?: bits)?\)$"
)
RATE_RE = re.compile(r"^(\d+)/15$")
NUMS_RE = re.compile(r"\d+(\s+\d+)*")


def fail(msg):
    sys.exit(f"gen_bit_interleaver_tables: {msg}")


def annex_b_lines(pdf_path):
    lines = []
    for page in pypdf.PdfReader(pdf_path).pages:
        page_lines = [ln.strip() for ln in (page.extract_text() or "").split("\n")]
        # Running header ("ATSC A/322...") then the page number.
        if page_lines and re.match(r"ATSC\s+A/322", page_lines[0]):
            page_lines = page_lines[2:]
        lines.extend(page_lines)
    start = next((i for i, ln in enumerate(lines) if CAPTION_RE.match(ln)), None)
    if start is None:
        fail("Table B.1.1 not found; is this the A/322 PDF?")
    end = next((i for i in range(start, len(lines)) if lines[i].startswith("Annex C:")), None)
    if end is None:
        fail("end of Annex B (Annex C heading) not found")
    return lines[start:end]


def parse(lines):
    tables = {}  # (ninner, mod) -> {rate numerator: [pi]}
    key = None
    header = []
    rate = None
    for ln in lines:
        m = CAPTION_RE.match(ln)
        if m:
            key = (int(m.group(4)), m.group(3))
            if key in tables:
                fail(f"duplicate table {key}")
            tables[key] = {}
            header, rate = [], None
            continue
        if key is None or not ln:
            continue
        m = RATE_RE.match(ln)
        if m:
            rate = int(m.group(1))
            if rate in tables[key]:
                fail(f"{key}: rate {rate}/15 listed twice")
            tables[key][rate] = []
            continue
        if not NUMS_RE.fullmatch(ln):
            continue  # captions, column headings, section titles
        values = [int(t) for t in ln.split()]
        if rate is None:
            header.extend(values)
        else:
            tables[key][rate].extend(values)
    return tables


def check(tables):
    for ninner in (64800, 16200):
        ngroup = ninner // 360
        mods = MODS if ninner == 64800 else MODS[:4]
        for mod in mods:
            t = tables.get((ninner, mod))
            if t is None:
                fail(f"table for {mod} N={ninner} not found")
            if sorted(t) != list(range(2, 14)):
                fail(f"{mod} N={ninner}: rates {sorted(t)}")
            for rate, pi in t.items():
                if sorted(pi) != list(range(ngroup)):
                    fail(f"{mod} N={ninner} rate {rate}/15: not a permutation of 0..{ngroup - 1}")


def wrap(values):
    lines, cur = [], "   "
    for v in values:
        tok = f" {v},"
        if len(cur) + len(tok) > 100:
            lines.append(cur)
            cur = "   "
        cur += tok
    lines.append(cur)
    return "\n".join(lines)


def emit(tables):
    out = []
    w = out.append
    w("// SPDX-License-Identifier: MPL-2.0")
    w("// SPDX-FileCopyrightText: 2026 Alfred Wanga")
    w("")
    w("#pragma once")
    w("")
    w("// Group-wise interleaving orders pi(j), ATSC A/322 Annex B")
    w("// (Tables B.1.1-B.1.6, B.2.1-B.2.4), used by Section 6.2.2: Y_j = X_pi(j).")
    w("//")
    w("// Generated by scripts/gen_bit_interleaver_tables.py from the standard's")
    w("// PDF; do not edit by hand.")
    w("")
    w("#include <cstdint>")
    w("")
    w("namespace atsc3 {")
    w("namespace fec {")
    w("")
    w("// clang-format off")
    names_long, names_short = [], []
    for ninner, suffix, mods, names in (
        (64800, "long", MODS, names_long),
        (16200, "short", MODS[:4], names_short),
    ):
        for mod in mods:
            row = []
            for rate in range(2, 14):
                name = f"k_group_order_{suffix}_{mod.lower()}_{rate}_15"
                w(f"inline constexpr uint8_t {name}[] = {{")
                w(wrap(tables[(ninner, mod)][rate]))
                w("};")
                row.append(name)
            names.append(row)
    w("")
    w("// Indexed [modulation][config::CodeRate]; modulation in config::Modulation")
    w("// order (QPSK, 16QAM, 64QAM, 256QAM, 1024QAM, 4096QAM).")
    w("inline constexpr const uint8_t* k_group_order_long[6][12] = {")
    for row in names_long:
        w("  {" + ", ".join(row) + "},")
    w("};")
    w("// 16200-bit codes: QPSK to 256QAM only.")
    w("inline constexpr const uint8_t* k_group_order_short[4][12] = {")
    for row in names_short:
        w("  {" + ", ".join(row) + "},")
    w("};")
    w("// clang-format on")
    w("")
    w("}  // namespace fec")
    w("}  // namespace atsc3")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        fail("usage: gen_bit_interleaver_tables.py A322.pdf > lib/fec/bit_interleaver_tables.h")
    tables = parse(annex_b_lines(sys.argv[1]))
    check(tables)
    sys.stdout.write(emit(tables))


if __name__ == "__main__":
    main()
