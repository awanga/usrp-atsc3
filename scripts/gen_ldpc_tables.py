"""Generate lib/fec/ldpc_tables.h from the ATSC A/322 PDF (Annex A).

Annex A lists, for each of the 24 LDPC codes (rates 2/15-13/15 at
Ninner = 64800 and 16200), the parity-accumulator addresses of the first
bit of every 360-bit group (Tables A.1.1-A.1.12 and A.2.1-A.2.12). The
encoding procedure that consumes them is A/322 Section 6.1.3; the code
type and the Type A parity split (M1, M2) come from Tables 6.4-6.7 and are
restated below as constants.

Usage:
  scripts/gen_ldpc_tables.py A322-2026-06.pdf > lib/fec/ldpc_tables.h

The PDF is published by ATSC (https://www.atsc.org/atsc-documents/) and is
not redistributed here. A/322:2018 and A/322:2026-06 give byte-identical
output. Requires pypdf (BSD-3-Clause; 6.13.0 used).

Every table is checked before anything is emitted: the row count must be
the number of 360-bit groups the encoder consumes (Nouter/360 for Type B,
(Nouter + M1)/360 for Type A), each row must be strictly ascending (as
printed), and every address must lie inside the parity range. Any failure
exits nonzero rather than emitting a partial header.
"""

import re
import sys

import pypdf

# (rate numerator, Ninner) -> (type, M1) ; M1 is 0 for Type B.
# Tables 6.4 (type), 6.5 and 6.6 (Type A M1).
CODES = {}
for n in range(2, 14):
    for ninner in (64800, 16200):
        CODES[(n, ninner)] = ("B", 0)
CODES.update(
    {
        (2, 64800): ("A", 1800),
        (3, 64800): ("A", 1800),
        (4, 64800): ("A", 1800),
        (5, 64800): ("A", 1440),
        (7, 64800): ("A", 1080),
        (2, 16200): ("A", 3240),
        (3, 16200): ("A", 1080),
        (4, 16200): ("A", 1080),
        (5, 16200): ("A", 720),
    }
)

CAPTION_RE = re.compile(r"^Table A\.([12])\.(\d+) Rate = (\d+)/15 \(Ninner = (\d+)\)$")


def fail(msg):
    sys.exit(f"gen_ldpc_tables: {msg}")


def annex_a_lines(pdf_path):
    lines = []
    for page in pypdf.PdfReader(pdf_path).pages:
        page_lines = [ln.strip() for ln in (page.extract_text() or "").split("\n")]
        # Running header ("ATSC A/322...") then the page number.
        if page_lines and re.match(r"ATSC\s+A/322", page_lines[0]):
            page_lines = page_lines[2:]
        lines.extend(page_lines)
    start = next(
        (i for i, ln in enumerate(lines) if CAPTION_RE.match(ln)),
        None,
    )
    if start is None:
        fail("Table A.1.1 not found; is this the A/322 PDF?")
    end = next(
        (i for i in range(start, len(lines)) if lines[i].startswith("Annex B:")),
        None,
    )
    if end is None:
        fail("end of Annex A (Annex B heading) not found")
    return lines[start:end]


def split_tables(lines):
    tables = {}
    key = None
    for ln in lines:
        m = CAPTION_RE.match(ln)
        if m:
            key = (int(m.group(3)), int(m.group(4)))
            if key in tables:
                fail(f"duplicate caption for rate {key[0]}/15 N={key[1]}")
            tables[key] = []
            continue
        if not ln or ln.startswith("A.2 ") or ln.startswith("A.1 "):
            continue
        if not re.fullmatch(r"\d+(\s+\d+)*", ln):
            fail(f"unexpected text in rate {key[0]}/15 N={key[1]}: {ln!r}")
        tables[key].append([int(t) for t in ln.split()])
    return tables


def check(key, rows):
    n, ninner = key
    ctype, m1 = CODES[key]
    nouter = ninner * n // 15
    minner = ninner - nouter
    groups = (nouter + m1) // 360
    if len(rows) != groups:
        fail(f"rate {n}/15 N={ninner}: {len(rows)} rows, expected {groups}")
    for r, row in enumerate(rows):
        if any(b <= a for a, b in zip(row, row[1:])):
            fail(f"rate {n}/15 N={ninner} row {r} not strictly ascending: {row}")
        if row[-1] >= minner:
            fail(f"rate {n}/15 N={ninner} row {r}: address {row[-1]} >= {minner}")
        if ctype == "A" and r >= nouter // 360 and min(row) < m1:
            # Rows for the M1 parity groups feed the M2 (identity) part only.
            fail(f"rate {n}/15 N={ninner} row {r}: parity row addresses M1 part")


def emit(tables):
    out = []
    w = out.append
    w("// SPDX-License-Identifier: MPL-2.0")
    w("// SPDX-FileCopyrightText: 2026 Alfred Wanga")
    w("")
    w("#pragma once")
    w("")
    w("// LDPC parity-accumulator address tables, ATSC A/322 Annex A")
    w("// (Tables A.1.1-A.1.12, A.2.1-A.2.12).")
    w("//")
    w("// Generated by scripts/gen_ldpc_tables.py from the standard's PDF; do not")
    w("// edit by hand. Row r holds the addresses for the first bit of 360-bit")
    w("// group r; the encoding rule that expands them is A/322 Section 6.1.3")
    w("// (Type A: Q1/Q2 offsets over the M1/M2 split; Type B: Qldpc offsets).")
    w("")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("")
    w("namespace atsc3 {")
    w("namespace fec {")
    w("")
    w("struct LdpcTable {")
    w("    size_t ninner;              // codeword length")
    w("    size_t nouter;              // information bits")
    w("    bool type_a;                // A/322 Table 6.4")
    w(
        "    size_t m1;                  // Type A dual-diagonal parity length (0 for Type B)"
    )
    w("    size_t num_rows;            // 360-bit groups listed")
    w("    const uint16_t* row_start;  // num_rows + 1 offsets into addresses")
    w("    const uint16_t* addresses;")
    w("};")
    w("")
    w("// clang-format off")
    order = []
    for ninner, suffix in ((64800, "long"), (16200, "short")):
        for n in range(2, 14):
            key = (n, ninner)
            rows = tables[key]
            name = f"k_ldpc_{suffix}_{n}_15"
            starts = [0]
            for row in rows:
                starts.append(starts[-1] + len(row))
            if starts[-1] > 0xFFFF:
                fail(f"{name}: {starts[-1]} addresses overflow uint16_t offsets")
            w(f"inline constexpr uint16_t {name}_start[] = {{")
            w(wrap(starts))
            w("};")
            w(f"inline constexpr uint16_t {name}_addr[] = {{")
            w(wrap([a for row in rows for a in row]))
            w("};")
            w("")
            ctype, m1 = CODES[key]
            order.append(
                f"    {{{ninner}, {ninner * n // 15}, {str(ctype == 'A').lower()}, "
                f"{m1}, {len(rows)}, {name}_start, {name}_addr}},"
            )
    w("// Indexed [short_codeword][config::CodeRate]: long codes first.")
    w("inline constexpr LdpcTable k_ldpc_tables[2][12] = {")
    w("  {")
    w("\n".join(order[:12]))
    w("  },")
    w("  {")
    w("\n".join(order[12:]))
    w("  },")
    w("};")
    w("// clang-format on")
    w("")
    w("}  // namespace fec")
    w("}  // namespace atsc3")
    return "\n".join(out) + "\n"


def wrap(values):
    lines, cur = [], "   "
    for v in values:
        tok = f" {v},"
        if len(cur) + len(tok) > 100:
            lines.append(cur)
            cur = "   "
        cur += tok
    lines.append(cur)
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        fail("usage: gen_ldpc_tables.py A322.pdf > lib/fec/ldpc_tables.h")
    tables = split_tables(annex_a_lines(sys.argv[1]))
    missing = sorted(set(CODES) - set(tables))
    if missing:
        fail(f"tables not found: {missing}")
    for key in CODES:
        check(key, tables[key])
    sys.stdout.write(emit(tables))


if __name__ == "__main__":
    main()
